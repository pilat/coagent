#!/bin/sh

set -eu

# Byte order: a locale-dependent sort would reorder the record between hosts.
LC_ALL=C
export LC_ALL

values=scripts/ratchet.values
arch_config=.go-arch-lint.yml

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT HUP INT TERM

measure() {
	# Directories the Go tool skips never hold production code.
	find cmd internal \
		-type d \( -name testdata -o -name '_*' -o -name '.*' \) -prune -o \
		-type f -name '*.go' ! -name '*_test.go' -print > "$work/files"
	[ -s "$work/files" ] || { echo "ratchet: no production Go files found"; exit 1; }

	awk '
		{
			file = $0
			dir = file
			sub(/\/[^\/]*$/, "", dir)
			while ((status = (getline line < file)) > 0) {
				lines[dir]++
				rest = line
				while (match(rest, /\/\/[ \t]*nolint/)) {
					nolint++
					rest = substr(rest, RSTART + RLENGTH)
				}
			}
			if (status < 0) { print "ratchet: cannot read " file > "/dev/stderr"; failed = 1 }
			close(file)
		}
		END {
			if (failed) exit 1
			for (dir in lines) printf "lines %s %d\n", dir, lines[dir]
			printf "nolint total %d\n", nolint
		}
	' "$work/files" > "$work/go"

	# Fails closed on any shape it cannot count, so reformatting cannot hide an edge.
	awk -v config="$arch_config" '
		function bad(why) { printf "%s:%d: ratchet cannot count this %s: %s\n", config, FNR, why, $0 > "/dev/stderr"; failed = 1 }
		/^commonComponents:/ { bad("top-level key") }
		/^deps:/ { in_deps = 1; next }
		/^[^ #]/ { in_deps = 0 }
		!in_deps || /^[ ]*(#.*)?$/ { next }
		/^  [a-z][a-z0-9_-]*:[ ]*$/ { component = $1; sub(/:$/, "", component); next }
		/^    anyProjectDeps:[ ]*true[ ]*$/ { any++; next }
		/^    (anyProjectDeps|anyVendorDeps):[ ]*(true|false)[ ]*$/ { next }
		/^    mayDependOn:[ ]*\[[^]]*\][ ]*$/ {
			list = $0
			sub(/^[^[]*\[/, "", list)
			sub(/\].*$/, "", list)
			count = split(list, names, ",")
			edges[component] += count
			total += count
			next
		}
		{ bad("deps line") }
		END {
			if (failed) exit 1
			for (component in edges) printf "edges %s %d\n", component, edges[component]
			printf "edges total %d\n", total
			printf "anyprojectdeps total %d\n", any
		}
	' "$arch_config" > "$work/arch"

	cat "$work/go" "$work/arch" > "$work/unsorted"
	sort "$work/unsorted" > "$work/current"
}

case "${1:-}" in
"" | record) ;;
*) echo "usage: $0 [record]"; exit 2 ;;
esac

measure

if [ "${1:-}" = record ]; then
	{
		echo "# Generated by make ratchet.record. Raising a value is a deliberate act: docs/coding-style.md."
		cat "$work/current"
	} > "$values"
	echo "ratchet: recorded $(wc -l < "$work/current") values in $values"
	exit 0
fi

[ -s "$values" ] || { echo "$values is missing or empty; run make ratchet.record"; exit 1; }

awk -v values="$values" '
	NR == FNR {
		if ($0 ~ /^#/ || NF == 0) next
		if (NF != 3 || $3 !~ /^[0-9]+$/) { printf "%s:%d: malformed line: %s\n", values, FNR, $0; malformed = 1; next }
		record[$1 " " $2] = $3 + 0
		next
	}
	malformed { exit 1 }
	{
		key = $1 " " $2
		measured[key] = 1
		old = (key in record) ? record[key] : 0
		if ($3 + 0 > old) {
			printf "%s: %s grew from %d to %d\n", values, key, old, $3
			grew = 1
		} else if ($3 + 0 < old) {
			below++
		}
	}
	END {
		if (malformed) exit 1
		for (key in record) if (!(key in measured) && record[key] > 0) below++
		if (grew) { print "raise it deliberately in this PR and say why in the description (make ratchet.record rewrites the file)"; exit 1 }
		if (below) printf "ratchet: %d value(s) below the record; make ratchet.record lowers them\n", below
	}
' "$values" "$work/current"
